// Turns dist/index.html into dist/worker.js: a Cloudflare Worker (ES module)
// that serves the whole game from memory. Run after `vite build`.
import { readFileSync, writeFileSync } from 'node:fs'

const html = readFileSync('dist/index.html', 'utf8')
const worker = `// Auto-generated by tools/build-worker.mjs. Do not edit by hand.
const HTML = ${JSON.stringify(html)};
export default {
  async fetch(req) {
    const url = new URL(req.url);
    // Tiny version endpoint so we can check what is live.
    if (url.pathname === '/version.json') {
      return new Response(JSON.stringify({ build: ${JSON.stringify(new Date().toISOString())} }), { headers: { 'content-type': 'application/json' } });
    }
    // Every other path serves the single-page game.
    return new Response(HTML, { headers: { 'content-type': 'text/html; charset=utf-8', 'cache-control': 'no-cache' } });
  },
};
`
writeFileSync('dist/worker.js', worker)
console.log('dist/worker.js', (worker.length / 1024).toFixed(1), 'KB')
